namespace kajarlabs.Framework.Input;

/// <summary>
/// Platform-agnostic mouse button identifiers.
/// </summary>
public enum MouseButton
{
    /// <summary>
    /// Primary (left) mouse button.
    /// </summary>
    Left = 0,

    /// <summary>
    /// Middle (wheel) mouse button.
    /// </summary>
    Middle = 1,

    /// <summary>
    /// Secondary (right) mouse button.
    /// </summary>
    Right = 2,

    /// <summary>
    /// Fourth mouse button (commonly back / XButton1).
    /// </summary>
    Button4 = 3,

    /// <summary>
    /// Fifth mouse button (commonly forward / XButton2).
    /// </summary>
    Button5 = 4,
}
