using kajarlabs.Framework.Scene;

namespace kajarlabs.Framework.Input;

/// <summary>
/// Base payload for keyboard key press and release events.
/// </summary>
public abstract class KeyboardEvent : UIEvent
{
    /// <summary>
    /// Initializes a new instance of the <see cref="KeyboardEvent"/> class.
    /// </summary>
    protected KeyboardEvent(InputState currentState, Key key, Drawable? target = null)
        : base(currentState, target)
    {
        Key = key;
    }

    /// <summary>
    /// Gets the keyboard key associated with this event.
    /// </summary>
    public Key Key { get; }
}

/// <summary>
/// Raised when a keyboard key is pressed or repeats while held.
/// </summary>
public sealed class KeyDownEvent : KeyboardEvent
{
    /// <summary>
    /// Initializes a new instance of the <see cref="KeyDownEvent"/> class.
    /// </summary>
    public KeyDownEvent(InputState currentState, Key key, bool repeat = false, Drawable? target = null)
        : base(currentState, key, target)
    {
        Repeat = repeat;
    }

    /// <summary>
    /// Gets a value indicating whether this event was generated by automatic key repeat.
    /// </summary>
    public bool Repeat { get; }
}

/// <summary>
/// Raised when a keyboard key is released.
/// </summary>
public sealed class KeyUpEvent : KeyboardEvent
{
    /// <summary>
    /// Initializes a new instance of the <see cref="KeyUpEvent"/> class.
    /// </summary>
    public KeyUpEvent(InputState currentState, Key key, Drawable? target = null)
        : base(currentState, key, target)
    {
    }
}

/// <summary>
/// Raised when committed UTF-8 text input is delivered to the focused drawable or non-positional queue.
/// </summary>
public sealed class TextInputEvent : UIEvent
{
    /// <summary>
    /// Initializes a new instance of the <see cref="TextInputEvent"/> class.
    /// </summary>
    public TextInputEvent(InputState currentState, string text, Drawable? target = null)
        : base(currentState, target)
    {
        ArgumentNullException.ThrowIfNull(text);
        Text = text;
    }

    /// <summary>
    /// Gets the committed text string.
    /// </summary>
    public string Text { get; }
}
