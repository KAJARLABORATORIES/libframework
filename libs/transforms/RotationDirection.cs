namespace kajarlabs.Framework.Scene.Transforms;

/// <summary>
/// Specifies the rotational direction for continuous spin animations.
/// </summary>
public enum RotationDirection
{
    /// <summary>
    /// Rotates clockwise (increasing positive angles in degrees).
    /// </summary>
    Clockwise,

    /// <summary>
    /// Rotates counterclockwise (decreasing angles in degrees).
    /// </summary>
    Counterclockwise,
}
